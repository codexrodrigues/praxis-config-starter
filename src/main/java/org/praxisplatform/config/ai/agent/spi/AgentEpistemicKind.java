package org.praxisplatform.config.ai.agent.spi;

/**
 * Neutral epistemic classification for quantitative, rule-based, simulated, or inferential outputs
 * surfaced to operational AI agents.
 *
 * <p>
 * Keeps epistemic distinctions universal inside {@code praxis-config-starter} without introducing a
 * compile dependency on external statistical/intelligence runtime modules.
 * </p>
 */
public enum AgentEpistemicKind {

    /** Exact legal, contractual, accounting, or mathematical determination backed by deterministic rules. */
    DETERMINISTIC_LAW,

    /** Statistical estimate or risk score with bounded empirical uncertainty. */
    CALIBRATED_PROBABILITY,

    /** Scenario projection generated by simulation models (what-if / Monte Carlo / policy sensitivity). */
    STOCHASTIC_SIMULATION,

    /** Observational or quasi-experimental hypothesis indicating correlation or plausible causal direction. */
    CAUSAL_HYPOTHESIS,

    /** Resource allocation or constrained mathematical optimization output under stated assumptions. */
    OPTIMIZATION_RESULT
}
